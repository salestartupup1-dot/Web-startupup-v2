// Run after downloading the selected sources to coverage/article-cover-sources.
// Resizing/encoding only; source provenance and licenses stay in the manifest.
import fs from 'node:fs/promises';
import sharp from 'sharp';

const sources = JSON.parse(await fs.readFile('content/articles/cover-sources.json', 'utf8'));
const metadata = {};
await fs.mkdir('public/articles/photos', { recursive: true });
for (const [key, source] of Object.entries(sources)) {
  const image = sharp(`coverage/article-cover-sources/${key}.jpg`).rotate();
  const base = `/articles/photos/${key}`;
  await image.clone().resize(960, 640, { fit: 'cover' }).webp({ quality: 82 }).toFile(`public${base}.webp`);
  await image.clone().resize(1200, 800, { fit: 'cover' }).jpeg({ quality: 84, mozjpeg: true }).toFile(`public${base}.jpg`);
  metadata[key] = { cover: `${base}.webp`, coverSocial: `${base}.jpg`, coverAlt: source.alt,
    coverCredit: { name: source.author, url: source.source, license: source.license, licenseUrl: source.licenseUrl,
      illustrative: source.license === 'Pexels', attributionRequired: source.license === 'CC BY-SA 4.0' } };
}
await fs.writeFile('content/articles/covers.js', `// Generated by scripts/prepare-article-photos.mjs. See cover-sources.json for provenance.\nexport const ARTICLE_COVERS = ${JSON.stringify(metadata, null, 2)};\n`);
console.log(`Prepared ${Object.keys(metadata).length} article covers and share images.`);

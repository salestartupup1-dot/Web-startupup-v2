export const locationPath = location => `/${encodeURIComponent(location.slug)}`;
export const findSeoLocation = slug => [...SEO_LOCATIONS, ...SEO_LANDINGS].find(item => item.slug === slug);
export function seoLocationFromPath(path = '') {
  try { return findSeoLocation(decodeURIComponent(path.split('?')[0]).replace(/^\/|\/$/g, '')); }
  catch { return undefined; }
}
export function seoLocationFromSearch(search = {}) {
  if (!['location_group', 'main_location', 'district'].includes(search.type)) return undefined;
  return [...SEO_LOCATIONS, ...SEO_LANDINGS].find(location => location.name === search.value);
}
// Normalize both record and comparison text. NFKC decomposes Thai sara am (ำ).
export const normalizeDistrict = value => {
  const text = String(value || '').normalize('NFKC').replace(/\s+/g, '');
  const prefix = ['อำเภอ', 'อ.', 'เขต'].map(item => item.normalize('NFKC')).find(item => text.startsWith(item));
  return prefix ? text.slice(prefix.length) : text;
};
const pathumDistricts = ['เมืองปทุมธานี', 'คลองหลวง', 'ธัญบุรี', 'ลำลูกกา', 'ลาดหลุมแก้ว', 'สามโคก', 'หนองเสือ'].map(normalizeDistrict);
export function matchesSeoLocation(property, location) {
  if (location?.kind) return matchesLandingCriteria(property, location)
    && (!location.pathumOnly || matchesSeoLocation(property, SEO_LOCATIONS.find(item => item.name === 'ปทุมธานี')));
  const district = normalizeDistrict(property.district);
  if (!district || !location) return false;
  const province = String(property.province || '').normalize('NFKC').replace(/\s+/g, '').replace(/^(จังหวัด|จ\.)/, '');
  if (province && province !== 'ปทุมธานี'.normalize('NFKC')) return false;
  if (location.name === 'รังสิต') return ['คลองหลวง', 'ธัญบุรี'].map(normalizeDistrict).includes(district);
  if (location.name === 'ปทุมธานี') {
    return pathumDistricts.includes(district);
  }
  return district === normalizeDistrict(location.name);
}

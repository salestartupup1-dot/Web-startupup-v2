export const locationPath = location => `/${encodeURIComponent(location.slug)}`;
export const findSeoLocation = slug => SEO_LOCATIONS.find(item => item.slug === slug);
export function seoLocationFromPath(path = '') {
  try { return findSeoLocation(decodeURIComponent(path.split('?')[0]).replace(/^\/|\/$/g, '')); }
  catch { return undefined; }
}
export function seoLocationFromSearch(search = {}) {
  if (!['location_group', 'main_location', 'district'].includes(search.type)) return undefined;
  return SEO_LOCATIONS.find(location => location.name === search.value);
}
const normalizeArea = value => String(value || '').normalize('NFKC').replace(/\s+/g, '')
  .replace(/คลองหนึ่ง/g, 'คลอง1').replace(/คลองสอง/g, 'คลอง2').replace(/คลองสาม/g, 'คลอง3').replace(/คลองสี่/g, 'คลอง4');
export function matchesSeoLocation(property, location) {
  const main = normalizeArea(property.main_location || property.district);
  const district = normalizeArea(property.district);
  const sub = normalizeArea(property.sub_location || property.subdistrict);
  const fields = [main, district, sub];
  const khlong = fields.some(v => v.startsWith('คลองหลวง'));
  const canal = `${main} ${sub}`.match(/คลอง(\d+)/)?.[1];
  const phayom = fields.some(v => v.includes('พยอม'));
  const thanya = fields.some(v => v.startsWith('ธัญบุรี')) || (khlong && canal === '4');
  const khlongGroup = phayom || (khlong && (!canal || ['1', '2', '3'].includes(canal)));
  const lam = fields.some(v => v.startsWith('ลำลูกกา') || v.startsWith('สายไหม'));
  if (location.name === 'คลองหลวง') return khlongGroup;
  if (location.name === 'ธัญบุรี') return thanya;
  if (location.name === 'ลำลูกกา') return lam;
  if (location.name === 'รังสิต') return khlongGroup || thanya || main === 'รังสิต';
  if (location.name === 'ปทุมธานี') {
    const province = normalizeArea(property.province);
    if (province) return province === 'ปทุมธานี' || province === 'จ.ปทุมธานี' || province === 'จังหวัดปทุมธานี';
    return !phayom && !fields.some(v => v.startsWith('สายไหม'))
      && fields.some(v => location.areas.some(area => v.startsWith(normalizeArea(area))));
  }
  return false;
}

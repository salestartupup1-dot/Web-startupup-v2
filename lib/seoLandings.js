const normalized = value => String(value || '').normalize('NFKC').trim();
export function matchesLandingCriteria(property, landing) {
  if (property.inventoryState !== 'available' || property.badge === 'Sold Out' || isPartnerProperty(property)) return false;
  const category = normalized(property.category).replace(/\s+/g, '');
  if (landing.kind === 'townhouse') return ['ทาวน์เฮาส์', 'ทาวน์เฮาส์หลังริม'].includes(category);
  if (landing.kind === 'corner-townhouse') return category === 'ทาวน์เฮาส์หลังริม';
  if (landing.kind === 'detached') return category === 'บ้านเดี่ยว';
  if (landing.kind === 'pruksa') {
    // Anchor the project name, so e.g. ราชพฤกษ์ or unrelated substring matches
    // cannot be treated as part of this project family.
    const project = normalized(property.project_name).replace(/^(?:หมู่บ้าน|ม\.)\s*/, '');
    return /^พฤกษา(?:วิลเลจ|วิลล์)?(?=$|\s|[0-9A-Za-z-])/u.test(project);
  }
  if (landing.kind === 'budget') {
    const text = normalized(property.price).replace(/,/g, '');
    const price = /^\d+(?:\.\d+)?$/.test(text) ? Number(text) : NaN;
    return Number.isFinite(price) && price > 0 && price <= landing.maxPrice;
  }
  return false;
}
